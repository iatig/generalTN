#
# -------------------------   create_Heron_grid   ---------------------
#

def create_ibm_grid(grid_type):
	
	match grid_type:
		
		case 'PRETZEL':
			n = 28
			LAYERS = LAYERS_PRETZEL
			
		case 'HERON_R2':
			n = 156
			LAYERS = LAYERS_HERON_R2

		case 'HERON_R3':
			n = 156
			LAYERS = LAYERS_HERON_R3

		case 'HERON_65q':
			n = 156
			LAYERS = LAYERS_HERON_65q

		case 'HERON_51q':
			n = 156
			LAYERS = Heron_51q


		case 'HERON_65q_tree':
			n = 156
			LAYERS = LAYERS_HERON_65q_TREE
			
		case 'EAGLE_KYIV':
			n = 127
			LAYERS = LAYERS_EAGLE_KYIV
			
		case 'HERON_49q':
			n = 156
			LAYERS = Heron_layers_49q
		
		case _:
			raise ValueError("grid_type not supported")
	
	
	pre_e_list = {}
	
	for layer in LAYERS:
		for (i,j) in layer:
			
			#
			# Make sure always i<j
			#
			if i>j:
				i,j = j,i
			
			if i in pre_e_list:
				pre_e_list[i].append( (i,j) )
			else:
				pre_e_list[i] = [(i,j)]
				
			if j in pre_e_list:
				pre_e_list[j].append( (i,j) )
			else:
				pre_e_list[j] = [(i,j)]
				
	e_list = []
	
	for i in range(n):
		if i not in pre_e_list:
			continue
			
		pre_es = pre_e_list[i]
		
		es = []
		for (i1,j1) in pre_es:

			e = f'e{i1}-{j1}'
			es.append(e)
		
		if es != []:
			e_list.append(es)
			
	e_dict = calc_e_dict(e_list)
	
	layers = []
	for layer in LAYERS:
		L = []
		for (i,j) in layer:
			e = f'e{i}-{j}'
			L.append(e)
		layers.append(L)
	

	return e_list, e_dict, layers


#
# ---------------------  create_ibm_grid_from_layers  ------------------
#
def create_ibm_grid_from_layers(n: int, input_layers: list[list[tuple[int, int]]]):
	pre_e_list = [[] for i in range(n)]

	for layer in input_layers:
		for (i, j) in layer:
			pre_e_list[i].append((i, j))
			pre_e_list[j].append((i, j))

	ang = [pi, 0, pi / 2, 1.5 * pi]  # Left/Right/Up/Down angles

	e_list = []
	angles_list = []
	for i, es in enumerate(pre_e_list):

		es_list = [None] * 4

		for (i1, j1) in es:

			e = f'e{i1}-{j1}'

			#
			# Decide if the edge is L/R/U/D. So first understand what is j.
			#
			if i == i1:
				j = j1
			else:
				j = i1

			if j == i - 1:
				es_list[0] = e  # Left edge
			elif j == i + 1:
				es_list[1] = e  # Right edge
			elif j < i - 1:
				es_list[2] = e  # Up edge
			elif j > i + 1:
				es_list[3] = e  # Down edge
			else:
				print("Error - unidentified edge at ", i, j)
				exit(0)

		new_es = []
		angles = []
		for k in range(4):
			if es_list[k] is not None:
				new_es.append(es_list[k])
				angles.append(ang[k])

		e_list.append(new_es)
		angles_list.append(angles)

	e_dict = calc_e_dict(e_list)

	layers = []
	for layer in input_layers:
		L = []
		for (i, j) in layer:
			e = f'e{i}-{j}'
			L.append(e)
		layers.append(L)

	return e_list, e_dict, angles_list, layers
